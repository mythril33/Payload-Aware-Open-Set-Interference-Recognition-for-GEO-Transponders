"""Verify a B2-base artifact and optionally simulate eight missing-carrier twins.

python scripts/check_b2_base.py --data data/b2-base-pilot \
    --out runs/b2-base-pilot/physics.json --check-missing

Forced diagnostic twins are never appended to the production dataset. This
checks physics and artifact execution; it does not train a recognition model.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import time

import numpy as np

from geosim.b2_dataset import b2_fingerprint, iter_b2_shards, read_b2_manifest
from geosim.b2_protocol import B2Config, LABELS, ROLE_COUNTS, ROLE_STARTS
from geosim.b2_scenarios import sample_scene
from geosim.dataset import _generator_provenance
from geosim.polarization import ReceiverCalibration


def check(data, *, check_missing=False):
    root = Path(data)
    manifest = read_b2_manifest(root)
    current_source = manifest["request"]["source_sha256"] == _generator_provenance()
    report = {"protocol": manifest["protocol"], "parent_protocol": manifest["parent_protocol"],
              "benchmark_complete": manifest["benchmark_complete"], "data_fingerprint": b2_fingerprint(root),
              "generator_source_matches_current": current_source, "roles": {},
              "calibration": manifest["calibration"], "n_observations": 0, "n_scenario_groups": 0,
              "n_missing_carrier_observations": 0,
              "artifact_bytes": sum(path.stat().st_size for path in root.rglob("*") if path.is_file()),
              "recognition_metrics": None,
              "scope": "Known physical observations; no classifier training or recognition-quality claim."}
    reference = None
    for role, info in manifest["roles"].items():
        report["roles"][role] = {key: info[key] for key in ("n_samples", "n_scenarios", "per_label")}
        report["n_observations"] += info["n_samples"]
        report["n_scenario_groups"] += info["n_scenarios"]
        for shard in iter_b2_shards(root, role):
            report["n_missing_carrier_observations"] += int(shard["plan_consistency"].sum())
            if reference is None:
                group = int(shard["seed"][0])
                selected = np.flatnonzero(shard["seed"] == group)
                reference = {int(shard["label"][index]): (shard["meta"][index], shard["mask"][index])
                             for index in selected}
    # This inventory uses only predeclared RNG draws, not simulated test scores.
    report["reserved_group_missing_inventory"] = {
        role: {"n_groups": ROLE_COUNTS[role],
               "n_missing": sum(np.random.default_rng([group, 1813]).uniform() < 0.15
                                for group in range(ROLE_STARTS[role], ROLE_STARTS[role] + ROLE_COUNTS[role]))}
        for role in ROLE_STARTS if role != "test-matched"}
    for item in report["reserved_group_missing_inventory"].values():
        item["n_missing"] = int(item["n_missing"])
    if check_missing:
        if not current_source:
            raise ValueError("fresh diagnostic twins require data generated by the current source")
        if reference is None or set(reference) != set(range(len(LABELS))):
            raise ValueError("the first shard must contain a complete eight-label group")
        if any(record["plan_consistency"] != 0 for record, _ in reference.values()):
            raise ValueError("forced-missing diagnostics require an all-active reference group")
        config = B2Config(**manifest["config"])
        calibration = ReceiverCalibration.load(root / "receiver_calibration.npz")
        rows, started = [], time.perf_counter()
        for index, name in enumerate(LABELS):
            original, mask = reference[index]
            twin = sample_scene(name, original["scenario_id"], config, missing_carrier=True,
                                calibration=calibration)
            if not np.array_equal(twin.mask_db.astype(np.float16), mask) or twin.meta["plans"] != original["plans"]:
                raise AssertionError("carrier absence changed the operator plan")
            if twin.meta["config"] != original["config"] or twin.meta["gain_mode"] != original["gain_mode"]:
                raise AssertionError("carrier absence changed nominal link/gain settings")
            if twin.meta["plan_consistency"] != 1:
                raise AssertionError("missing-carrier diagnostic lost its auxiliary target")
            dropped = twin.meta["dropped_carrier"]
            pol = dropped["polarization"]
            if not twin.meta["active_planned_power"][pol] < original["active_planned_power"][pol]:
                raise AssertionError("active load was renormalized after dropping a carrier")
            if not np.isfinite(twin.spec_db).all():
                raise AssertionError("nonfinite missing-carrier observation")
            if name == "clean" and not twin.meta["paths"][pol]["actual_ibo_db"] > original["paths"][pol]["actual_ibo_db"]:
                raise AssertionError("clean missing-carrier twin did not increase actual back-off")
            if name == "carrier_under_carrier" and not twin.meta["active_carriers"][0][twin.meta["event"]["victim_index"]]:
                raise AssertionError("under-carrier event has no active victim")
            rows.append({"label": name, "scenario_id": original["scenario_id"], "dropped_carrier": dropped,
                         "operator_plan_unchanged": True, "nominal_gain_unchanged": True,
                         "active_planned_power_before": original["active_planned_power"],
                         "active_planned_power_after": twin.meta["active_planned_power"],
                         "actual_ibo_db_before": [path["actual_ibo_db"] for path in original["paths"]],
                         "actual_ibo_db_after": [path["actual_ibo_db"] for path in twin.meta["paths"]],
                         "event_parameters_match_reference": original["event"] == twin.meta["event"]})
        report["forced_missing_diagnostics"] = {"n_observations": len(rows), "part_of_dataset": False,
                                                 "elapsed_seconds": time.perf_counter() - started, "rows": rows}
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True)
    parser.add_argument("--out", required=True, help="JSON report path")
    parser.add_argument("--check-missing", action="store_true")
    args = parser.parse_args()
    result = check(args.data, check_missing=args.check_missing)
    path = Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(result, indent=2, allow_nan=False) + "\n")
    print(f"Verified {result['n_observations']} known observations; wrote {path}")


if __name__ == "__main__":
    main()
