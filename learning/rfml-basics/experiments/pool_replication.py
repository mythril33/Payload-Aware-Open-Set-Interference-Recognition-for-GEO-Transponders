"""Pool an original campaign with its replication (PREREGISTRATION_V3.md, part A).

Reads two aggregates written by run_campaign.py or run_campaign2.py (the
original, seeds 0-4, and the replication on fresh seeds 5-9) and writes one
pooled aggregate: every metric over all seeds, and for each hypothesis the
original verdict, the replication verdict (predicted sign in >= 4 of 5 fresh
seeds) and the pooled count (>= 8 of 10).

Usage:
    .venv/bin/python experiments/pool_replication.py \
        --original experiments/campaign --replication experiments/campaign_rep \
        --out experiments/pooled/campaign1
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np


def required_positive(n_seeds: int) -> int:
    """Predicted sign in at least 80% of the seeds: 4 of 5, 8 of 10."""
    return math.ceil(0.8 * n_seeds)


def _summary(values: list[float]) -> dict:
    arr = np.asarray(values, dtype=np.float64)
    return {
        "per_seed": [float(v) for v in arr],
        "mean": float(arr.mean()),
        "sd": float(arr.std(ddof=1)) if arr.size > 1 else None,
        "min": float(arr.min()),
        "max": float(arr.max()),
    }


def pool(original: dict, replication: dict) -> dict:
    """Combine two aggregates. Raises if their seeds overlap or their designs differ."""
    seeds_a = list(original["provenance"]["seeds"])
    seeds_b = list(replication["provenance"]["seeds"])
    if set(seeds_a) & set(seeds_b):
        raise ValueError(f"seed sets overlap: {sorted(set(seeds_a) & set(seeds_b))}")
    if original["provenance"]["scale"] != replication["provenance"]["scale"]:
        raise ValueError("the two campaigns ran at different scales")
    if original["failures"] or replication["failures"]:
        raise ValueError("a campaign with recorded failures cannot be pooled")

    metrics: dict[str, dict] = {}
    for stage, stage_metrics in original["metrics"].items():
        metrics[stage] = {}
        for name, summary in stage_metrics.items():
            rep = replication["metrics"][stage][name]
            metrics[stage][name] = _summary(summary["per_seed"] + rep["per_seed"])

    hypotheses: dict[str, dict] = {}
    for name, h in original["hypotheses"].items():
        rep = replication["hypotheses"][name]
        diffs = list(h["per_seed_diff"]) + list(rep["per_seed_diff"])
        n_pos = sum(d > 0 for d in diffs)
        hypotheses[name] = {
            "seeds": seeds_a + seeds_b,
            "per_seed_diff": diffs,
            "mean_diff": float(np.mean(diffs)),
            "sd_diff": float(np.std(diffs, ddof=1)),
            "original": {"n_positive": h["n_positive"], "n_seeds": h["n_seeds"], "supported": h["supported"]},
            "replication": {
                "n_positive": rep["n_positive"],
                "n_seeds": rep["n_seeds"],
                "supported": rep["supported"],
            },
            # "replicated" means: the fresh seeds alone meet the pre-registered criterion.
            "replicated": bool(rep["n_positive"] >= required_positive(rep["n_seeds"])),
            "pooled": {
                "n_positive": n_pos,
                "n_seeds": len(diffs),
                "required_positive": required_positive(len(diffs)),
                "supported": bool(n_pos >= required_positive(len(diffs))),
            },
        }

    return {
        "provenance": {
            "original": original["provenance"],
            "replication": replication["provenance"],
            "seeds": seeds_a + seeds_b,
        },
        "metrics": metrics,
        "hypotheses": hypotheses,
    }


def write_summary_md(pooled: dict, path: Path) -> None:
    lines = [
        "# Pooled summary (generated by pool_replication.py — do not edit)",
        "",
        f"Seeds {pooled['provenance']['seeds']}.",
        "",
        "| stage | metric | mean | sd | min | max |",
        "|---|---|---|---|---|---|",
    ]
    for stage, stage_metrics in pooled["metrics"].items():
        for name, s in stage_metrics.items():
            lines.append(f"| {stage} | {name} | {s['mean']:.3f} | {s['sd']:.3f} | {s['min']:.3f} | {s['max']:.3f} |")
    lines += [
        "",
        "## Hypotheses (a - b, predicted > 0)",
        "",
        "| hypothesis | mean diff | original | replication | replicated | pooled | pooled supported |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, h in pooled["hypotheses"].items():
        o, r, p = h["original"], h["replication"], h["pooled"]
        lines.append(
            f"| {name} | {h['mean_diff']:+.3f} | {o['n_positive']}/{o['n_seeds']} | "
            f"{r['n_positive']}/{r['n_seeds']} | {h['replicated']} | {p['n_positive']}/{p['n_seeds']} | {p['supported']} |"
        )
    path.write_text("\n".join(lines) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--original", type=Path, required=True)
    ap.add_argument("--replication", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    pooled = pool(
        json.loads((args.original / "aggregate.json").read_text()),
        json.loads((args.replication / "aggregate.json").read_text()),
    )
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "aggregate.json").write_text(json.dumps(pooled, indent=2, allow_nan=False))
    write_summary_md(pooled, args.out / "aggregate_summary.md")
    print(f"pooled {len(pooled['provenance']['seeds'])} seeds -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
