@pytest.mark.parametrize("mutation", ["extra", "wrong-schema", "wrong-signer-key", "duplicate-principal", "duplicate-key",
                                    "wildcard", "options", "rsa", "invalid-base64", "trailing-key-comment", "duplicate-purpose",
                                    "missing-purpose", "unknown-purpose", "wire-length", "signers-not-list"])
def test_malformed_pinned_policy_never_invokes_crypto(policy, monkeypatch, mutation):
    signer = policy["signers"][0]
    if mutation == "extra": policy["override"] = True
    if mutation == "wrong-schema": policy["schema"] = "untrusted"
    if mutation == "wrong-signer-key": signer["private_key"] = "forbidden"
    if mutation == "duplicate-principal": policy["signers"].append(copy.deepcopy(signer))
    if mutation == "duplicate-key": policy["signers"].append(dict(signer, principal="another-claim"))
    if mutation == "wildcard": signer["principal"] = "*"
    if mutation == "options": signer["public_key"] = 'command="evil" ' + signer["public_key"]
    if mutation == "rsa": signer["public_key"] = signer["public_key"].replace("ssh-ed25519", "ssh-rsa")
    if mutation == "invalid-base64": signer["public_key"] = "ssh-ed25519 !!!!"
    if mutation == "trailing-key-comment": signer["public_key"] += " untrusted-comment"
    if mutation == "duplicate-purpose": signer["namespaces"] *= 2
    if mutation == "missing-purpose": signer["namespaces"] = []
    if mutation == "unknown-purpose": signer["namespaces"] = ["b2-production"]
    if mutation == "wire-length": signer["public_key"] = signer["public_key"][:-4]
    if mutation == "signers-not-list": policy["signers"] = {}
    monkeypatch.setattr(S.subprocess, "run", lambda *a, **k: pytest.fail("bad policy reached cryptographic process"))
    report = verify(policy, b"not-a-signature")
    assert not report["ok"]
    closed(report)


