    if mutation == "namespace": args["namespace"] = "b2-ci"
    if mutation == "pin": args["policy_sha256"] = "0" * 64
    if mutation == "unknown-root":
        policy["signers"][0]["public_key"] = keys["unknown"][1]
        # Keep independently supplied old pin: document-controlled replacement fails.
    report = S.verify_signature(payload, signature, **args)
    assert not report["ok"]
    closed(report)


