@pytest.mark.parametrize("mutation", ["record", "signature", "principal", "namespace", "pin", "unknown-root"])
def test_forgery_alteration_and_identity_mismatch(keys, policy, tmp_path, mutation):
    signature = sign(keys, tmp_path=tmp_path)
    args = dict(policy=policy, policy_sha256=pin(policy), principal=PRINCIPAL, namespace="b2-dr04")
