import subprocess

import pytest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("e17_signatures_under_test", ROOT / "scripts/b2_e17_signatures.py")
S = importlib.util.module_from_spec(spec)
spec.loader.exec_module(S)
PRINCIPAL = "researcher-fixture"
PAYLOAD = b"E17 FABRICATED TEST EVIDENCE ONLY\nNo real researcher approval.\n"


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def pin(policy):
    return sha(S.canonical(policy).encode())


@pytest.fixture(scope="module")
def keys(tmp_path_factory):
    root = tmp_path_factory.mktemp("e17-fabricated-signing-keys-only")
    result = {}
    for name in ("allowed", "unknown"):
        private = root / name
        subprocess.run(["/usr/bin/ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", "E17-fabricated-fixture-only", "-f", str(private)],
                       check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        public = " ".join(private.with_suffix(".pub").read_text().split()[:2])
        result[name] = (private, public)
    return result


def sign(keys, *, key="allowed", payload=PAYLOAD, namespace="b2-dr04", tmp_path):
    target = tmp_path / "E17_FABRICATED_EVIDENCE_ONLY"
    target.write_bytes(payload)
    subprocess.run(["/usr/bin/ssh-keygen", "-Y", "sign", "-f", str(keys[key][0]), "-n", namespace, str(target)],
                   check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return target.with_suffix(".sig").read_bytes()


@pytest.fixture
def policy(keys):
    return {"schema": S.SCHEMA, "signers": [{"principal": PRINCIPAL, "public_key": keys["allowed"][1],
                                            "namespaces": ["b2-dr04", "b2-revocation", "b2-ci"]}]}


def verify(policy, signature, **kwargs):
    params = dict(policy=policy, policy_sha256=pin(policy), principal=PRINCIPAL, namespace="b2-dr04")
    params.update(kwargs)
    return S.verify_signature(PAYLOAD, signature, **params)


def closed(report):
    assert report["execution_permitted"] is False
    assert report["authorizes_nothing"] is True
    json.dumps(report, allow_nan=False)


def test_genuine_crypto_validates_fabricated_temporary_key_only(keys, policy, tmp_path):
    signature = sign(keys, tmp_path=tmp_path)
    original = copy.deepcopy(policy)
    report = verify(policy, signature)
    assert report["ok"] is True
    assert report["status"] == "SIGNATURE_VERIFIED"
    assert report["verified_principal"] == PRINCIPAL
    assert report["payload_sha256"] == sha(PAYLOAD)
    assert report["policy_sha256"] == pin(policy)
    assert len(report["verifier_sha256"]) == 64
    assert policy == original
    closed(report)


@pytest.mark.parametrize("policy,pinned", [(None, None), ({"schema": S.SCHEMA, "signers": []}, None),
                                         ({"schema": S.SCHEMA, "signers": []}, "pinned")])
def test_real_default_missing_trust_root_is_blocked(policy, pinned, monkeypatch):
    monkeypatch.setattr(S.subprocess, "run", lambda *a, **k: pytest.fail("verification without a configured trust root"))
    report = S.verify_signature(PAYLOAD, b"untrusted", policy=policy,
                                policy_sha256=pin(policy) if pinned == "pinned" else pinned,
                                principal=PRINCIPAL, namespace="b2-dr04")
    assert report["ok"] is False
    assert report["status"] == "BLOCKED_TRUST_ROOT_MISSING"
    closed(report)


